/** Resolve `typescript` from this package or from the caller's, whichever has it. */
function loadTypeScript() {
  const bases = [import.meta.url, pathToFileURL(join(process.cwd(), "package.json")).href];
  const failures = [];
  for (const base of bases) {
    try {
      return createRequire(base).resolve("typescript");
    } catch (err) {
      failures.push(`${base}: ${err.message}`);
    }
  }
  throw new Error(
    `cannot resolve the typescript package.\n${failures.join("\n")}\n` +
      `Run this from a package that has typescript installed ` +
      `(clients/ts or clients/sync, after a pnpm install).`,
  );
}

/**
 * Every fenced code block in `markdown`, with the 1-based line its fence opens
 * on. Blocks whose language is not code, and blocks explicitly opted out, are
 * dropped.
 */
function extractBlocks(markdown) {
  const lines = markdown.split("\n");
  const blocks = [];
  let open = null;
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i] ?? "";
    const fence = /^```(\w*)\s*$/.exec(line);
    if (open === null) {
      if (!fence) continue;
      const language = (fence[1] ?? "").toLowerCase();
      const skipped = (lines[i - 1] ?? "").trim() === SKIP_MARKER;
      open = { language, startLine: i + 1, body: [], skipped };
      continue;
    }
    if (line.startsWith("```")) {
      if (CODE_LANGUAGES.has(open.language) && !open.skipped) {
        blocks.push({ startLine: open.startLine, source: open.body.join("\n") });
      }
      open = null;
      continue;
    }
    open.body.push(line);
  }
  if (open !== null) throw new Error(`unterminated code fence opened at line ${open.startLine}`);
  return blocks;
}

/** Every identifier a `context.ts` source makes available to a sample. */
function contextExports(source) {
  const names = new Set();
  for (const match of source.matchAll(/^export\s+(?:declare\s+)?(?:const|let|function|class|interface|type|enum)\s+(\w+)/gm)) {
    names.add(match[1]);
  }
  for (const match of source.matchAll(/^export\s+(?:type\s+)?\{([^}]*)\}/gm)) {
    for (const part of (match[1] ?? "").split(",")) {
      const name = part.trim().split(/\s+as\s+/).pop();
      if (name) names.add(name);
    }
  }
  return [...names];
}

/** Every identifier an import statement binds, so the context can skip it. */
function importedNames(statement) {
  const names = [];
  const named = /\{([^}]*)\}/.exec(statement);
  if (named) {
    for (const part of (named[1] ?? "").split(",")) {
      const name = part.trim().split(/\s+as\s+/).pop();
      if (name) names.push(name);
    }
  }
  const bare = /^\s*import\s+(?:type\s+)?(\w+)/.exec(statement);
  if (bare && bare[1] !== "type") names.push(bare[1]);
  const namespace = /\*\s+as\s+(\w+)/.exec(statement);
  if (namespace) names.push(namespace[1]);
  return names;
}

/**
 * Turn one block into a module: its own imports stay at the top (they cannot
 * live in a function), and the rest goes inside a nested scope so the block's
 * own declarations shadow the shared context instead of clashing with it.
 *
 * Returns the module source plus a map from each generated line to the README
 * line it came from, so a `tsc` diagnostic can be reported where an author can
 * act on it.
 */
function moduleFor(block, contextSpecifier, contextNames) {
  const imports = [];
  const body = [];
  let pending = null;
  block.source.split("\n").forEach((text, index) => {
    const readmeLine = block.startLine + 1 + index;
    if (pending !== null) {
      pending.text += `\n${text}`;
      if (text.includes("from ")) {
        imports.push(pending);
        pending = null;
      }
      return;
    }
    if (/^\s*import\s/.test(text)) {
      if (text.includes("from ") || text.trim().endsWith(";")) imports.push({ text, readmeLine });
      else pending = { text, readmeLine };
      return;
    }
    body.push({ text: text.length > 0 ? `    ${text}` : text, readmeLine });
  });
  if (pending !== null) imports.push(pending);

  const own = new Set(imports.map((entry) => entry.text).flatMap(importedNames));
  const fromContext = contextNames.filter((name) => !own.has(name));
  const generated = [
    ...imports,
    ...(fromContext.length === 0
      ? []
      : [{ text: `import { ${fromContext.join(", ")} } from ${JSON.stringify(contextSpecifier)};` }]),
    { text: "export async function __sample(): Promise<void> {" },
    // A nested scope, so a sample that declares its own `client` shadows the
    // shared one rather than redeclaring it.
    { text: "  {" },
    ...body,
    { text: "  }" },
    { text: "}" },
  ];
  const lineMap = [];
  const out = [];
  for (const entry of generated) {
    for (const line of entry.text.split("\n")) {
      out.push(line);
      lineMap.push(entry.readmeLine ?? null);
    }
  }
  return { source: `${out.join("\n")}\n`, lineMap };
}

function main() {
  const args = process.argv.slice(2);
  const onlyIndex = args.indexOf("--only");
  const only = onlyIndex === -1 ? null : args[onlyIndex + 1];

  const typescriptEntry = loadTypeScript();
  const packageDir = dirname(dirname(typescriptEntry));
  const nodeModules = dirname(packageDir);
  const projectRoot = join(nodeModules, ".powdb-readme-check");
  rmSync(projectRoot, { recursive: true, force: true });
  mkdirSync(projectRoot, { recursive: true });

  const selected = READMES.filter((r) => only === null || r.package === only);
  if (selected.length === 0) throw new Error(`no README configured for ${only}`);
  if (selected.some((r) => r.needs.includes("embedded"))) {
    try {
      readFileSync(EMBEDDED_TYPES);
    } catch {
      throw new Error(
        `${EMBEDDED_TYPES} is missing. It is generated by \`napi build\`, not ` +
          `checked in, so build the addon first:\n` +
          `  cd bindings/node && npm ci && npm run build\n` +
          `Or check one README on its own with --only @zvndev/powdb-client.`,
      );
    }
  }

  const files = [];
  const origins = new Map();
  for (const readme of selected) {
    const slug = readme.package.replace(/[^a-z0-9]+/gi, "-");
    const dir = join(projectRoot, slug);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "context.ts"), readme.context.trimStart());
    const contextNames = contextExports(readme.context);
    const blocks = extractBlocks(readFileSync(readme.file, "utf8"));
    if (blocks.length === 0) throw new Error(`no code samples found in ${readme.file}`);
    for (const block of blocks) {
      const name = `block-${String(block.startLine).padStart(4, "0")}.ts`;
      const path = join(dir, name);
      const module = moduleFor(block, "./context.js", contextNames);
      writeFileSync(path, module.source);
      files.push(path);
      const origin = { file: relative(REPO, readme.file), lineMap: module.lineMap };
      // tsc prints whichever of these two forms is shorter, so map both.
      origins.set(path, origin);
      origins.set(relative(process.cwd(), path), origin);
    }
  }

  writeFileSync(
    join(projectRoot, "tsconfig.json"),
    `${JSON.stringify(
      {
        compilerOptions: {
          target: "ES2022",
          module: "ES2022",
          moduleResolution: "bundler",
          lib: ["ES2022"],
          types: ["node"],
          strict: true,
          noEmit: true,
          esModuleInterop: true,
          forceConsistentCasingInFileNames: true,
          skipLibCheck: true,
          paths: {
            "@zvndev/powdb-client": [CLIENT_TYPES],
            "@zvndev/powdb-sync": [SYNC_TYPES],
            "@zvndev/powdb-embedded": [EMBEDDED_TYPES],
          },
        },
        files,
      },
      null,
      2,
    )}\n`,
  );

  const tsc = join(packageDir, "bin", "tsc");
  const run = spawnSync(process.execPath, [tsc, "-p", join(projectRoot, "tsconfig.json")], {
    encoding: "utf8",
  });
  const output = `${run.stdout ?? ""}${run.stderr ?? ""}`;
  if (run.status === 0) {
    console.log(`README samples type-check: ${files.length} block(s) across ${selected.length} package(s)`);
    rmSync(projectRoot, { recursive: true, force: true });
    return;
  }

  // tsc reports the generated file and its own line numbers; report the
  // README line the sample came from instead.
  const report = output.replace(
    /^(\S+)\((\d+),(\d+)\)/gm,
    (whole, path, line, column) => {
      const origin = origins.get(path);
      if (origin === undefined) return whole;
      const readmeLine = origin.lineMap[Number(line) - 1];
      return readmeLine === null || readmeLine === undefined
        ? `${origin.file}`
        : `${origin.file}:${readmeLine}:${column}`;
    },
  );
  process.stdout.write(report.endsWith("\n") ? report : `${report}\n`);
  console.error(`README samples failed to type-check. Generated project kept at ${projectRoot}`);
  process.exitCode = 1;
}

main();
